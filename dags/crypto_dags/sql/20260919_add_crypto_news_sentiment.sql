-- News data belongs to the central crypto schema. Apply this migration before
-- enabling the crypto_news DAGs; it does not modify the stock news tables.
BEGIN;

CREATE SCHEMA IF NOT EXISTS raw_crypto_data;

CREATE TABLE IF NOT EXISTS raw_crypto_data.news_articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url TEXT NOT NULL,
    url_hash CHAR(64) NOT NULL UNIQUE,
    title TEXT,
    snippet TEXT,
    source TEXT,
    language VARCHAR(10),
    published_at TIMESTAMPTZ NOT NULL,
    published_at_inferred BOOLEAN NOT NULL DEFAULT FALSE,
    first_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    meta JSONB,
    CONSTRAINT news_articles_seen_order CHECK (last_seen_at >= first_seen_at)
);
CREATE INDEX IF NOT EXISTS ix_crypto_news_articles_published
    ON raw_crypto_data.news_articles (published_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS raw_crypto_data.news_sentiments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    news_id BIGINT NOT NULL REFERENCES raw_crypto_data.news_articles(id) ON DELETE RESTRICT,
    coin_symbol TEXT NOT NULL,
    coin_name TEXT NOT NULL,
    classifier_version TEXT NOT NULL,
    model TEXT NOT NULL,
    prompt_hash CHAR(64) NOT NULL,
    input_hash CHAR(64) NOT NULL,
    input_snapshot JSONB NOT NULL,
    status VARCHAR(12) NOT NULL DEFAULT 'pending',
    attempts INTEGER NOT NULL DEFAULT 0,
    last_error TEXT,
    is_relevant BOOLEAN,
    relevance_verified BOOLEAN NOT NULL DEFAULT TRUE,
    sentiment VARCHAR(8),
    impact VARCHAR(6),
    confidence NUMERIC(4,3),
    reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    classified_at TIMESTAMPTZ,
    CONSTRAINT uq_crypto_news_sentiment_input
        UNIQUE (news_id, coin_symbol, classifier_version, input_hash),
    CONSTRAINT ck_crypto_news_sentiment_symbol
        CHECK (coin_symbol = upper(coin_symbol) AND btrim(coin_symbol) <> ''),
    CONSTRAINT ck_crypto_news_sentiment_status
        CHECK (status IN ('pending','failed','succeeded')),
    CONSTRAINT ck_crypto_news_sentiment_label
        CHECK (sentiment IS NULL OR sentiment IN ('positive','negative','neutral')),
    CONSTRAINT ck_crypto_news_sentiment_impact
        CHECK (impact IS NULL OR impact IN ('high','medium','low')),
    CONSTRAINT ck_crypto_news_sentiment_confidence
        CHECK (confidence IS NULL OR confidence BETWEEN 0 AND 1),
    CONSTRAINT ck_crypto_news_sentiment_attempts CHECK (attempts >= 0),
    CONSTRAINT ck_crypto_news_sentiment_complete CHECK (
        (status = 'succeeded' AND is_relevant IS NOT NULL
            AND sentiment IS NOT NULL AND impact IS NOT NULL AND classified_at IS NOT NULL)
        OR (status <> 'succeeded' AND sentiment IS NULL AND impact IS NULL
            AND classified_at IS NULL)
    )
);
CREATE INDEX IF NOT EXISTS ix_crypto_news_sentiment_coin_time
    ON raw_crypto_data.news_sentiments (coin_symbol, classifier_version, classified_at DESC);
CREATE INDEX IF NOT EXISTS ix_crypto_news_sentiment_work
    ON raw_crypto_data.news_sentiments (coin_symbol, created_at, id)
    WHERE status IN ('pending','failed');

CREATE TABLE IF NOT EXISTS raw_crypto_data.news_sentiment_aggregates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coin_symbol TEXT NOT NULL,
    window_start TIMESTAMPTZ NOT NULL,
    window_end TIMESTAMPTZ NOT NULL,
    classifier_version TEXT NOT NULL,
    score_version TEXT NOT NULL,
    model TEXT NOT NULL,
    pos INTEGER NOT NULL,
    neg INTEGER NOT NULL,
    neutral INTEGER NOT NULL,
    n_total INTEGER NOT NULL,
    inferred_count INTEGER NOT NULL,
    score NUMERIC(5,2),
    data_cutoff_at TIMESTAMPTZ NOT NULL,
    computed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_crypto_news_aggregate
        UNIQUE (coin_symbol, window_start, window_end, classifier_version, score_version),
    CONSTRAINT ck_crypto_news_aggregate_symbol
        CHECK (coin_symbol = upper(coin_symbol) AND btrim(coin_symbol) <> ''),
    CONSTRAINT ck_crypto_news_aggregate_window CHECK (window_start < window_end),
    CONSTRAINT ck_crypto_news_aggregate_counts CHECK (
        pos >= 0 AND neg >= 0 AND neutral >= 0 AND inferred_count >= 0
        AND n_total = pos + neg + neutral AND inferred_count <= n_total
    ),
    CONSTRAINT ck_crypto_news_aggregate_score CHECK (
        (n_total = 0 AND (score IS NULL OR
            (score_version = 'legacy-classified-v1' AND score = 50)))
        OR (n_total > 0 AND score BETWEEN 0 AND 100)
    )
);
CREATE INDEX IF NOT EXISTS ix_crypto_news_aggregate_coin_end
    ON raw_crypto_data.news_sentiment_aggregates (coin_symbol, window_end DESC);

CREATE TABLE IF NOT EXISTS raw_crypto_data.ai_longform_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coin_symbol TEXT NOT NULL,
    window_start TIMESTAMPTZ NOT NULL,
    window_end TIMESTAMPTZ NOT NULL,
    classifier_version TEXT NOT NULL,
    report_version TEXT NOT NULL,
    input_hash CHAR(64) NOT NULL,
    model TEXT NOT NULL,
    prompt_hash CHAR(64) NOT NULL,
    summary_md TEXT NOT NULL,
    source_snapshot JSONB NOT NULL,
    source_count INTEGER NOT NULL,
    tokens_used INTEGER,
    computed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_crypto_news_report
        UNIQUE (coin_symbol, window_start, window_end, report_version, input_hash),
    CONSTRAINT ck_crypto_news_report_symbol
        CHECK (coin_symbol = upper(coin_symbol) AND btrim(coin_symbol) <> ''),
    CONSTRAINT ck_crypto_news_report_window CHECK (window_start < window_end),
    CONSTRAINT ck_crypto_news_report_counts
        CHECK (source_count BETWEEN 0 AND 40 AND (tokens_used IS NULL OR tokens_used >= 0))
);
CREATE INDEX IF NOT EXISTS ix_crypto_news_report_coin_end
    ON raw_crypto_data.ai_longform_reports (coin_symbol, window_end DESC);

COMMIT;
